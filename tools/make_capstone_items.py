"""Capstone judge items (module 11). Author only; reads recordings, calls no model.

    .venv/Scripts/python.exe tools/make_capstone_items.py

Writes
  datasets/judge_items/capstone-trial1.jsonl   trial 1 of A's and the candidate's replies to the 72 refund tickets of dataset v2 (144 items),
                                               for every judge the 5.8 rule allows except v3
  datasets/judge_items/capstone-v3.jsonl       all five reply trials of both (720 items), for judge v3 (decision of 2026-11-05)
and reference/results/capstone-recordings-needed.md: what is already recorded and the exact record_judge.py commands that fill the gaps.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from evalkit import capstone  # noqa: E402
from evalkit.replay import Store  # noqa: E402
from product import reply  # noqa: E402

D = ROOT / "datasets/judge_items"


def items(trials):
    st = Store.load("reply")
    out = []
    for variant in capstone.VARIANTS:
        for c in capstone.refund_cases():
            key = reply.build_request(variant, c["text"])["key"]
            for t in trials:
                out.append({"id": f"{c['id']}-{variant}{t}", "ticket": c["text"], "reply": st.lookup(key, t)["output"]})
    return out


def write(name, rows):
    (D / name).write_text("".join(json.dumps(r, ensure_ascii=False, sort_keys=True) + "\n" for r in rows), encoding="utf-8")
    print(name, len(rows))


def main():
    write("capstone-trial1.jsonl", items((1,)))
    write("capstone-v3.jsonl", items((1, 2, 3, 4, 5)))
    allowed = capstone.allowed_judges()
    others = [j for j in allowed if j != "v3"]
    lines = ["# Capstone judge recordings needed", "",
             "Generated by `tools/make_capstone_items.py` (replay only). The 5.8 rule allows these judges on the labels in use: " + ", ".join(allowed) + ".",
             "Decision of 2026-11-05: every judge on trial 1 of A's and the candidate's refund replies on dataset v2 (72 tickets each), judge v3 on all five trials.",
             "A recorded verdict is found by request key, so nothing already judged is paid for twice (record_judge.py skips recorded keys).", "",
             "## What is recorded", "", "| judge | variant | verdicts needed | not recorded yet |", "|---|---|---|---|"]
    todo = []
    for j in allowed:
        for variant, d in capstone.judged(j).items():
            lines.append(f"| {j} | {variant} | {d['needed']} | {d['missing']} |")
            if d["missing"]:
                todo.append(j)
    lines += ["", "## Commands to run (the author, with the batch key; Windows paths)", ""]
    need_others = [j for j in others if j in todo]
    if need_others:
        lines += ["```", "python tools/record_judge.py --items datasets/judge_items/capstone-trial1.jsonl --judges " + " ".join(need_others), "```", ""]
    if "v3" in todo:
        lines += ["```", "python tools/record_judge.py --items datasets/judge_items/capstone-v3.jsonl --judges v3", "```", ""]
    if not need_others and "v3" not in todo:
        lines += ["Nothing is missing: every allowed judge is recorded for the capstone.", ""]
    lines += ["Add `--dry-run` first to print the number of calls. When the labels change (the author's confirmed labels), rerun this tool: the allowed set may change.", ""]
    (ROOT / "reference/results").mkdir(parents=True, exist_ok=True)
    (ROOT / "reference/results/capstone-recordings-needed.md").write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
